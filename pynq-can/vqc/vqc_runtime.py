"""Runtime VQC policy for the PYNQ PS: C kernel via ctypes, numpy fallback.

    pol = VQCPolicy.from_json("vqc_params.json")      # loads ./libvqc.so if present
    tau_ff = pol(obs8)

Build the kernel on the board:  make -C vqc   (or see vqc_kernel.c header)
"""
from __future__ import annotations

import ctypes
import json
import math
import os

import numpy as np

import vqc_model as M

HERE = os.path.dirname(os.path.abspath(__file__))


def fused_weights(theta) -> np.ndarray:
    """theta[72] -> W[4*6*8] float32: RZ(t2)*RY(t1)*RX(t0) as interleaved complex 2x2."""
    th = np.asarray(theta, dtype=np.float64).reshape(M.N_LAYERS, M.N_QUBITS, 3)
    out = np.zeros((M.N_LAYERS, M.N_QUBITS, 8), dtype=np.float32)
    for l in range(M.N_LAYERS):
        for q in range(M.N_QUBITS):
            u = (M._rz(th[l, q, 2]).astype(np.complex128) @ M._ry(th[l, q, 1]).astype(np.complex128)
                 @ M._rx(th[l, q, 0]).astype(np.complex128))
            out[l, q] = [u[0, 0].real, u[0, 0].imag, u[0, 1].real, u[0, 1].imag,
                         u[1, 0].real, u[1, 0].imag, u[1, 1].real, u[1, 1].imag]
    return out.ravel()


def write_perm_inc(path=os.path.join(HERE, "vqc_perm.inc")) -> None:
    with open(path, "w") as f:
        f.write("/* generated by vqc_runtime.write_perm_inc() -- CNOT ring 0->1->...->5->0 */\n")
        f.write(", ".join(str(int(v)) for v in M.PERM) + "\n")


class _Config(ctypes.Structure):
    _fields_ = [("W", ctypes.c_float * (M.N_LAYERS * M.N_QUBITS * 8)),
                ("feat_scale", ctypes.c_float * M.N_QUBITS),
                ("feat_index", ctypes.c_int * M.N_QUBITS),
                ("tau_max", ctypes.c_float),
                ("out_gain", ctypes.c_float)]


def fused_expval_numpy(x, W) -> float:
    """Numpy mirror of vqc_kernel.c (fused gates + permutation)."""
    W = np.asarray(W, dtype=np.float32).reshape(M.N_LAYERS, M.N_QUBITS, 8)
    psi = np.zeros(M.DIM, dtype=np.complex64)
    psi[0] = 1
    for l in range(M.N_LAYERS):
        for q in range(M.N_QUBITS):
            w = W[l, q]
            wm = np.array([[w[0] + 1j * w[1], w[2] + 1j * w[3]], [w[4] + 1j * w[5], w[6] + 1j * w[7]]])
            c, s = math.cos(x[q] / 2), math.sin(x[q] / 2)
            u = wm @ np.array([[c, -s], [s, c]])
            t = psi.reshape(2 ** q, 2, -1)
            psi = np.einsum("ij,ajb->aib", u, t).reshape(M.DIM).astype(np.complex64)
        psi = psi[M.PERM]
    return float(np.dot(np.abs(psi) ** 2, M.Z0_SIGN))


class VQCPolicy:
    def __init__(self, theta, feat_index=M.FEAT_INDEX, feat_scale=M.FEAT_SCALE,
                 tau_max=M.TAU_MAX, out_gain=M.OUT_GAIN, lib_path=None, use_c=True):
        self.theta = np.asarray(theta, dtype=np.float32)
        self.W = fused_weights(self.theta)
        self.feat_index = list(feat_index)
        self.feat_scale = np.asarray(feat_scale, dtype=np.float32)
        self.tau_max = float(tau_max)
        self.out_gain = float(out_gain)
        self.lib = None
        lib_path = lib_path or os.path.join(HERE, "libvqc.so")
        if use_c and os.path.exists(lib_path):
            self.lib = ctypes.CDLL(lib_path)
            self.lib.vqc_policy.restype = ctypes.c_float
            self.lib.vqc_policy.argtypes = [ctypes.POINTER(ctypes.c_float), ctypes.POINTER(_Config)]
            self.cfg = _Config()
            self.cfg.W[:] = self.W.tolist()
            self.cfg.feat_scale[:] = self.feat_scale.tolist()
            self.cfg.feat_index[:] = self.feat_index
            self.cfg.tau_max = self.tau_max
            self.cfg.out_gain = self.out_gain
            self._obs = (ctypes.c_float * 8)()
            self._cfg_ref = ctypes.byref(self.cfg)

    @classmethod
    def from_json(cls, path, **kw):
        with open(path) as f:
            d = json.load(f)
        return cls(d["theta"], d.get("feat_index", M.FEAT_INDEX), d.get("feat_scale", M.FEAT_SCALE),
                   d.get("tau_max", M.TAU_MAX), d.get("out_gain", M.OUT_GAIN), **kw)

    @property
    def backend(self) -> str:
        return "c" if self.lib is not None else "numpy"

    def features(self, obs):
        f = np.asarray(obs, dtype=np.float32)[self.feat_index]
        return math.pi * np.tanh(self.feat_scale * f)

    def __call__(self, obs) -> float:
        if self.lib is not None:
            o = self._obs
            for i in range(8):
                o[i] = obs[i]
            return self.lib.vqc_policy(o, self._cfg_ref)
        z = fused_expval_numpy(self.features(obs), self.W)
        return self.tau_max * math.tanh(self.out_gain * z)


