"""Export reference vectors for the C kernel / HLS testbench.

    python export_vectors.py [params.json]   -> test_vectors.npz, ../hls/tb_vectors.h
Without a params file random angles are used (kernel correctness only).
"""
import os
import sys

import numpy as np

import vqc_model as M
import vqc_runtime as RT

HERE = os.path.dirname(os.path.abspath(__file__))


def main():
    rng = np.random.default_rng(7)
    theta = M.load_params(sys.argv[1]) if len(sys.argv) > 1 else rng.uniform(-3, 3, M.N_PARAMS).astype(np.float32)
    obs = np.concatenate([rng.normal(0, s, (64, 1)) for s in (0.01, 0.2, 0.02, 1.0, 0.3, 1.0, 10.0, 0.3)],
                         axis=1).astype(np.float32)
    tau = np.array([M.policy_numpy(o, theta) for o in obs], dtype=np.float32)
    np.savez(os.path.join(HERE, "test_vectors.npz"), theta=theta, obs=obs, tau=tau)

    W = RT.fused_weights(theta)
    fl = lambda a: ", ".join(f"{float(v):.9e}f" for v in np.ravel(a))
    with open(os.path.join(HERE, "..", "hls", "tb_vectors.h"), "w") as f:
        f.write("/* generated by vqc/export_vectors.py */\n#define TB_N %d\n" % len(obs))
        f.write("static const float TB_W[%d] = {%s};\n" % (W.size, fl(W)))
        f.write("static const float TB_FEAT_SCALE[6] = {%s};\n" % fl(M.FEAT_SCALE))
        f.write("static const int TB_FEAT_INDEX[6] = {%s};\n" % ", ".join(map(str, M.FEAT_INDEX)))
        f.write("static const float TB_TAU_MAX = %s;\nstatic const float TB_OUT_GAIN = %s;\n" % (fl([M.TAU_MAX]), fl([M.OUT_GAIN])))
        f.write("static const float TB_OBS[%d][8] = {\n%s};\n" % (len(obs), ",\n".join("{%s}" % fl(o) for o in obs)))
        f.write("static const float TB_TAU[%d] = {%s};\n" % (len(tau), fl(tau)))
    print(f"{len(obs)} vectors, tau range [{tau.min():.3f}, {tau.max():.3f}]")


if __name__ == "__main__":
    main()
